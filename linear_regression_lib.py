def check_ols_vs_reference(cache_dir, keys, mu, sd, blocks=("own", "ctx"), exclude=(), lags=LAGS):
    """GATE 3: the streamed least-squares path (standardise, QR-accumulate, solve) against an
    independent least-squares solve on the same materialised rows: scikit-learn's
    LinearRegression when it is installed, otherwise the algorithm it runs, in numpy (centre
    the inputs and the target, then an SVD-based least-squares solve).

    Coefficients are not unique when inputs are collinear, so the FITTED VALUES are compared.

    The reference scales each input by its own standard deviation over these rows (as a
    StandardScaler would), independently of (mu, sd). Without the scaling, a relative singular-
    value cutoff applied to raw inputs whose units span six orders of magnitude (positions, drag
    forces in N, penetration depths) drops genuine directions of the small-unit columns: on LR4's
    1,618 inputs this made the raw-input reference a WORSE least-squares fit than ours (job 882173:
    max difference 1.2e-3 of std(y), reference RMSE 19.9188 N against ours 19.9175 N); scaled, the
    two agree to 2.6e-8.
    Returns (rows, max |difference| / std(y), name of the reference)."""
    X, y = materialise(cache_dir, keys, blocks, lags)
    p = X.shape[1]
    M = np.empty((X.shape[0], p + 2))
    M[:, 0] = 1.0
    M[:, 1:p + 1] = (X - mu[:p]) / sd[:p]
    M[:, -1] = y
    fac = dict(R=_square(_qr_update(None, M), p + 2), n=float(y.size))
    w, _ = ls_solve(fac, p, exclude=exclude)
    ours = M[:, :p + 1] @ w
    del M
    Xk = X[:, [j for j in range(p) if j not in set(exclude)]]
    del X
    xm, xs = Xk.mean(axis=0), Xk.std(axis=0)
    Xs = (Xk - xm) / np.where(xs > 0.0, xs, 1.0)       # the reference's own scaling
    del Xk
    try:
        from sklearn.linear_model import LinearRegression
        ref = LinearRegression().fit(Xs, y).predict(Xs)
        name = "scikit-learn's LinearRegression on standardised inputs"
    except ImportError:
        ym = y.mean()
        coef = np.linalg.lstsq(Xs, y - ym, rcond=None)[0]
        ref = Xs @ coef + ym
        name = "numpy lstsq on standardised, centred inputs (scikit-learn's algorithm)"
    return int(y.size), float(np.max(np.abs(ours - ref)) / np.std(y)), name


