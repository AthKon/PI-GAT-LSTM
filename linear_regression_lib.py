"""Linear-regression baselines for the Stage-1 (matched-resolution) reconstruction task.

Companion module of Linear_Regression.ipynb. It lives in a .py file (not in the notebook)
for one reason: the training and evaluation passes run in a process pool, and on Windows a
worker process can only call functions it can import.

What is reused from Stage 1, unchanged (module `stage1_verbatim`, generated by
_build_linear_regression_nb.py straight from the Stage-1 notebook code):
  * the input features  -- build_mooring_graph, resample_fe_output, and the per-window
    feature code of MooringSequenceDatasetPositionTension. The batched port below is checked
    against the class itself and must agree exactly (GATE 2 in the notebook);
  * the split           -- build_leakage_aware_splits and _cap_split_windows, run on
    header-only stand-ins, then the evaluation-mask screen _sr22_filter_windows;
  * the metrics         -- compute_physical_metrics_per_target per window, then the
    aggregation of evaluate() (cell 8f268a8b) and the CSV layout of test_model() (cell
    d75ee9f2), ported below as EvalAccumulator and write_test_outputs.

The four linear models (a ladder: each adds information the GAT+BiLSTM has):
  LR0_static     T = tension0, the station's static (t = 0) tension. No fit.
  LR1_pointwise  ordinary least squares on the station's own 34 model inputs at one instant
                 (12 static + 22 dynamic): exactly what the GAT receives per station.
  LR2_line       LR1 + the 9 motion-derived channels of the fairlead, of the two neighbouring
                 stations and their mean along the line, at the same instant.
  LR3_lagged     LR2 + the station's and the fairlead's 9 channels at lags of +-0.1 .. +-5 s,
                 i.e. a non-causal linear filter over the window, like the bidirectional LSTM.
  LR4_lagged40   LR3 + the same channels at every 1 s out to +-40 s: the filter's memory spans
                 most of the 100 s window (lags are clamped at its edges, as the BiLSTM also
                 sees only the window). LR3's columns are LR4's leading columns. LR4 has its own
                 standardiser and its own caches, so LR0-LR3 are computed exactly as before.

All are fitted by ordinary least squares, the exact minimiser of the mean squared error.
The fit is streamed: every block of rows [1, z, y] (z = standardised inputs) updates the
triangular factor R of a QR decomposition, R <- qr([R; block]). This is the backward-stable
way to solve least squares in one pass; the normal equations (X^T X) square the condition
number and lose near-collinear directions (measured on a small subset: 1.3e-5 excess squared
error, against 2e-8 for QR). LR3 adds a small ridge term, picked on the validation split.
"""
