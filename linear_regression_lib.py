                idx = (torch.tensor([s])[:, None] + torch.arange(WINDOW_LEN)[None])
                dyn = batched_dynamic_features(rec["x"][idx], rec["z"][idx], graph, env_row)
                X = design(graph, dyn, FULL_BLOCKS, lags)[0].numpy().astype(np.float64)
