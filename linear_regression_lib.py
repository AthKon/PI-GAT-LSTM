def read_sample_table(path):
    """artifact_samples*.csv -> {(loc, case): sorted sample indices} (column bad_t)."""
    out = {}
    with open(path, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            out[(int(r["loc"]), int(r["case"]))] = sorted(int(t) for t in r["bad_t"].split())
    return out


def read_catalogue(path):
    """snap_catalogue*.csv -> ({(loc, case): sorted event samples}, {(loc, case, t): node})."""
    times, node = collections.defaultdict(list), {}
    with open(path, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            k = (int(r["loc"]), int(r["case"]))
            times[k].append(int(r["t"]))
            node[(k[0], k[1], int(r["t"]))] = int(r["node"])
    return {k: sorted(v) for k, v in times.items()}, node


