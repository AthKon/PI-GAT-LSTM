def predict_windows(cache_dir, keys, weights, mu, sd, lags=LAGS, stand=None):
    """{key: {'true': [W,N], rung: [W,N]}} for a handful of windows (figures).

    lags: the longest lag set among the rungs (its leading columns serve the shorter ones);
    stand: {rung: (mu, sd)} for a rung with its own standardiser (LR4)."""
