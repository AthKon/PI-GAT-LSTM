class StubDataset:
    """Header-only stand-in for MooringSequenceDatasetPositionTension.

    build_leakage_aware_splits reads only num_steps, window_len, len(), target_N and the
    graph's location/case ids, so no time series is opened to rebuild the split."""

    def __init__(self, lc, case, target_n, num_steps, window_len=WINDOW_LEN):
        self.num_steps = int(num_steps)
        self.window_len = int(window_len)
        self.target_N = int(target_n)
        self.graph_data = SimpleNamespace(batch_location_id=int(lc), case_id=int(case))

    def __len__(self):
        return self.num_steps - self.window_len + 1


def case_dir(cache_dir, lc, case):
    return Path(cache_dir) / f"loc{lc:02d}" / f"case_{case:04d}"


def record_lengths(cache_dir, corrupt=CORRUPT_CASES):
    """Record length of every in-use case, read from the .npy header only."""
    out = {}
    for lc in LOC_IDS:
        for case in range(1, N_CASES + 1):
            if (lc, case) in corrupt:
                continue
            out[(lc, case)] = int(np.load(case_dir(cache_dir, lc, case) / "x_abs.npy",
                                          mmap_mode="r").shape[0])
    return out


def regenerate_split(cache_dir, cfg, catenary, corrupt=CORRUPT_CASES):
    """The Stage-1 split, rebuilt with the verbatim utilities in Stage 1's dict order
    (location -> case -> node count, as build_lazy_load_case_datasets builds it).

    Returns flat window keys (loc, case, N, start): train, val, test (the published
    50,000-window draw) and test_screened (minus windows covering an evaluation-mask sample)."""
    lengths = record_lengths(cache_dir, corrupt)
    ds = {}
    for (lc, case), n in lengths.items():          # insertion order = loc -> case
        if n < cfg.window_len:
            continue
        for nc in LAYOUTS:
            ds[(lc, case, nc)] = StubDataset(lc, case, nc, n, cfg.window_len)
    sp = S1.build_leakage_aware_splits(ds, cfg)
    sp = S1._cap_split_windows(sp, cfg)
    screened = S1._sr22_filter_windows(sp["test"], catenary, cfg.window_len)
    flat = lambda pairs: [(k[0], k[1], k[2], int(w)) for k, w in pairs]   # noqa: E731
    return dict(train=flat(sp["train"]), val=flat(sp["val"]), test=flat(sp["test"]),
                test_screened=flat(screened), lengths=lengths)


