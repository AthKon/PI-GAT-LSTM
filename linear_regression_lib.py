def moments_to_standardiser(results):
    s1 = sum(r["s1"] for r in results)
    s2 = sum(r["s2"] for r in results)
    n = float(sum(r["n"] for r in results))
    mu = s1 / n
    sd = np.sqrt(np.maximum(s2 / n - mu * mu, 0.0))
    const = sd < (np.abs(mu) + 1.0) * 1e-6     # guard_constant_columns (FeatureStandardizer)
    sd = np.where(const, 1.0, sd)
    return mu, sd, const


def combine_factors(results, group=None):
    """Merge the tasks' factors (QR of the stacked factors), in task order.

    group=None merges both halves of a two-group pass."""
    Rs, n = [], 0.0
    for r in results:
        sel = range(r["R"].shape[0]) if group is None else (group,)
        for g in sel:
            Rs.append(r["R"][g])
            n += float(r["n"][g])
    R = np.linalg.qr(np.vstack(Rs), mode="r")
    return dict(R=_square(R, Rs[0].shape[1]), n=n)


def merge_factors(*facs):
    """One factor from several (e.g. the two halves of a pass): QR of the stacked factors."""
    q = facs[0]["R"].shape[1]
    R = np.linalg.qr(np.vstack([f["R"] for f in facs]), mode="r")
    return dict(R=_square(R, q), n=float(sum(f["n"] for f in facs)))


def excluded_inputs(names=None):
    """Indices (into the input columns) of the exact duplicates, removed before solving."""
    names = column_names() if names is None else names
    return sorted(names.index(n) for n in EXACT_DUPLICATES)


def ls_solve(fac, k, ridge=0.0, rcond=1e-12, exclude=()):
    """Least-squares weights [intercept, k inputs] from a factor of [1, z_1..z_p, y].

    Uses the leading k input columns (LR1 lies inside LR2 inside LR3) minus `exclude`, whose
    weights are returned as zero. Solved with numpy.linalg.lstsq on the small system
    R[:, cols] w = R[:, -1] (exact, since ||Z w - y|| = ||R [w; -1]||), whose singular values
    are those of the data themselves, not squared. The relative cutoff rcond gives any
    remaining exact collinearity (e.g. a column constant over the training set) the
    minimum-norm weights; the FITTED VALUES are the unique least-squares fit. ridge > 0 adds
    lambda * n * |w_inputs|^2 (lambda in units of the standardised variance; the intercept is
    not penalised)."""
    R, n = fac["R"], fac["n"]
    ex = set(int(j) for j in exclude)
    cols = [0] + [j + 1 for j in range(k) if j not in ex]
    A = R[:, cols]
    c = R[:, -1]
    if ridge:
        E = np.zeros((len(cols) - 1, len(cols)))
        E[:, 1:] = math.sqrt(ridge * n) * np.eye(len(cols) - 1)
        A = np.vstack([A, E])
        c = np.concatenate([c, np.zeros(len(cols) - 1)])
    w_s, _res, rank, sv = np.linalg.lstsq(A, c, rcond=rcond)
    w = np.zeros(k + 1)
    w[cols] = w_s
    kept = sv[sv > rcond * sv.max()]
    return w, dict(size=len(cols), rank=int(rank), cond=float(sv.max() / kept.min()),
                   ridge=float(ridge))


def fit_stats(w, fac):
    """MSE, RMSE and R^2 of weights w on the rows a factor was built from (exact:
    ||Z w - y||^2 = ||R [w; 0; -1]||^2 because Q has orthonormal columns)."""
    R, n = fac["R"], fac["n"]
    k = w.size - 1
    r = R[:, :k + 1] @ w - R[:, -1]
    sse = float(r @ r)
    sst = float(np.sum(R[1:, -1] ** 2))     # residual of the intercept-only fit
    return dict(mse=sse / n, rmse=math.sqrt(sse / n), r2=1.0 - sse / sst, n=n)


def static_weights(mu, sd, k):
    """LR0 (T = tension0) written as fixed linear weights, so fit_stats can score it."""
    w = np.zeros(k + 1)
    j = STATIC_NAMES.index("tension0")
    w[0], w[1 + j] = mu[j], sd[j]
    return w


def raw_coefficients(w, mu, sd):
    """Weights in physical input units: T = c0 + sum_j c_j x_j."""
    p = w.size - 1
    c = w[1:] / sd[:p]
    return float(w[0] - np.sum(c * mu[:p])), c


def restandardise(w, mu, sd, mu_new, sd_new):
    """The same linear model, written on inputs standardised with (mu_new, sd_new)."""
    p = w.size - 1
    c0, c = raw_coefficients(w, mu, sd)
    out = np.empty(p + 1)
    out[0] = c0 + float(np.sum(c * mu_new[:p]))
    out[1:] = c * sd_new[:p]
    return out


