def _tree_rss_gb():
    try:
        import psutil
        p = psutil.Process(os.getpid())
        return (p.memory_info().rss + sum(c.memory_info().rss for c in p.children(recursive=True))) / 1e9
    except Exception:
        return float("nan")


def _avail_gb():
    try:
        import psutil
        return psutil.virtual_memory().available / 1e9
    except Exception:
        return float("nan")


def _memory_check(label, rss_limit_gb, min_avail_gb):
    """Raise MemoryError before the machine runs short. The free-memory floor matters on
    Windows, which trims working sets under pressure, so RSS alone under-reports."""
    rss = _tree_rss_gb()
    if rss == rss and rss > rss_limit_gb:
        raise MemoryError(f"[{label}] process-tree RSS {rss:.1f} GB > {rss_limit_gb:.1f} GB")
    if min_avail_gb > 0:
        av = _avail_gb()
        if av == av and av < min_avail_gb:
            raise MemoryError(f"[{label}] free memory {av:.1f} GB < {min_avail_gb:.1f} GB; "
                              f"rerun with fewer workers (LR_WORKERS)")
    return rss


def run_parallel(tasks, n_workers, label, cache_dir=None, rss_limit_gb=None, min_avail_gb=None,
                 every=None):
    """Run tasks (in a process pool if n_workers > 1) and return results in TASK order.

    With cache_dir, each finished fit/moments task is saved as <tid>.npz and reused on a
    rerun, so an interrupted pass resumes. Results never depend on completion order.
    Memory is checked after every task (module settings RSS_LIMIT_GB / MIN_AVAIL_GB); on a
    breach, or any error, queued tasks are dropped and the workers are stopped at once."""
    rss_limit_gb = RSS_LIMIT_GB if rss_limit_gb is None else rss_limit_gb
    min_avail_gb = MIN_AVAIL_GB if min_avail_gb is None else min_avail_gb
    results = [None] * len(tasks)
    todo = []
    for i, t in enumerate(tasks):
        f = None if cache_dir is None else Path(cache_dir) / f"{t['tid']}.npz"
        if f is not None and f.exists():
            with np.load(f) as z:
                results[i] = {k: z[k] for k in z.files}
        else:
            todo.append(i)
    if len(todo) < len(tasks):
        print(f"[{label}] {len(tasks) - len(todo)} of {len(tasks)} tasks reused from {cache_dir}")
    if not todo:
        return results
    every = every or max(1, len(todo) // 40)
    t0, done = time.time(), 0

    def _store(i, res):
        nonlocal done
        results[i] = res
        if cache_dir is not None:
            Path(cache_dir).mkdir(parents=True, exist_ok=True)
            np.savez(Path(cache_dir) / f"{tasks[i]['tid']}.npz", **res)
        done += 1
        rss = _memory_check(label, rss_limit_gb, min_avail_gb)
        if done % every == 0 or done == len(todo):
            el = time.time() - t0
            eta = el / done * (len(todo) - done)
            print(f"[{label}] {done}/{len(todo)} tasks | {el / 60:5.1f} min elapsed | "
                  f"ETA {eta / 60:5.1f} min | RSS {rss:.1f} GB", flush=True)

    if n_workers <= 1:
        worker_init(max(1, torch.get_num_threads()))
        for i in todo:
            _store(i, run_task(tasks[i]))
        return results

    import multiprocessing as mp
    from concurrent.futures import ProcessPoolExecutor, as_completed
    # 'spawn' on every platform: the start method this code was validated with (Windows has no
    # other), and it never forks a Jupyter kernel that is running threads.
    ex = ProcessPoolExecutor(max_workers=min(int(n_workers), len(todo)),
                             mp_context=mp.get_context("spawn"), initializer=worker_init)
    try:
        fut = {ex.submit(run_task, tasks[i]): i for i in todo}
        for f in as_completed(fut):
            _store(fut[f], f.result())
    except BaseException:
        # The default shutdown would first run every queued task; stop now instead. The worker
        # list is taken first: shutdown() drops the executor's reference to it.
        procs = list((getattr(ex, "_processes", None) or {}).values())
        ex.shutdown(wait=False, cancel_futures=True)
        for proc in procs:
            proc.terminate()
        raise
    ex.shutdown(wait=True)
    return results


