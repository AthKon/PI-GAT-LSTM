def case_graph(arr, lc, case, n):
    """The station graph exactly as build_lazy_load_case_datasets (cell fbac801f) makes it."""
    x0 = torch.tensor(arr["x"][0], dtype=torch.float32)
    z0 = torch.tensor(arr["z"][0], dtype=torch.float32)
    t0 = torch.tensor(arr["T"][0], dtype=torch.float32)
    s0 = torch.tensor(arr["s0"], dtype=torch.float32)
    env_row = arr["env"]
    graph = S1.build_mooring_graph(
        x0_nodes=S1.resample_fe_output(x0.unsqueeze(0), n).squeeze(0),
        z0_nodes=S1.resample_fe_output(z0.unsqueeze(0), n).squeeze(0),
        tension0_nodes=S1.resample_fe_output(t0.unsqueeze(0), n).squeeze(0),
        s0_nodes=S1.resample_fe_output(s0.unsqueeze(0), n).squeeze(0),
        water_depth=float(env_row[0]),
        depths_current=[float(env_row[i]) for i in (3, 5, 7, 9, 11)],
    )
    graph.batch_location_id = lc
    graph.case_id = case
    return graph


def resampled_record(arr, n):
    """x, z and tension of the whole record at n stations. Resampling acts row by row
    (along the line), so slicing afterwards equals resampling each window."""
    return {k: S1.resample_fe_output(torch.tensor(arr[k], dtype=torch.float32), n)
            for k in ("x", "z", "T")}


# ----------------------------------------------------------------------------- features
def _time_gradient_b(sig, dt=S1.FEATURE_DT):
    """S1._time_gradient along dim 1 of [B, W, N], op for op."""
    grad = torch.empty_like(sig)
    grad[:, 1:-1] = (sig[:, 2:] - sig[:, :-2]) / (2.0 * dt)
    grad[:, 0] = (sig[:, 1] - sig[:, 0]) / dt
    grad[:, -1] = (sig[:, -1] - sig[:, -2]) / dt
    return grad


def _unit_tangents_b(x_abs, z_abs):
    """S1._unit_tangents along dim 2 of [B, W, N], op for op."""
    def _node_diff(sig):
        d = torch.empty_like(sig)
        d[..., 1:-1] = sig[..., 2:] - sig[..., :-2]
        d[..., 0] = sig[..., 1] - sig[..., 0]
        d[..., -1] = sig[..., -1] - sig[..., -2]
        return d
    dx = _node_diff(x_abs)
    dz = _node_diff(z_abs)
    mag = torch.sqrt(dx * dx + dz * dz).clamp_min(1e-8)
    return dx / mag, dz / mag


def batched_dynamic_features(x_abs, z_abs, graph, env_row, contact_tol=1e-6):
    """The 22 dynamic node inputs of a stack of windows, [B, W, N] -> [B, W, N, 22].

    A batched port of steps 3-6 of MooringSequenceDatasetPositionTension.__getitem__
    (sensor noise off). Same operations in the same order, so the result equals the class
    exactly (GATE 2)."""
    n = x_abs.shape[-1]
    node_len = torch.full((n,), float(graph.L0))
    node_len[0] *= 0.5
    node_len[-1] *= 0.5
    node_len = node_len.view(1, 1, n)

    x_vel = _time_gradient_b(x_abs)
    z_vel = _time_gradient_b(z_abs)

    z_bed = graph.z_bed_node.detach().cpu().view(1, 1, n)
    contact_flag = (z_abs <= z_bed + contact_tol).float()
    penetration = torch.clamp(z_bed - z_abs, min=0.0)
    submerged_w = graph.x[:, 9].detach().cpu().view(1, 1, n)
    contact_area = graph.diameter * node_len
    v_z = z_vel
    bed_reaction = torch.where(
        contact_flag > 0.0,
        submerged_w + (graph.k_b * penetration - graph.c_b * v_z) * contact_area,
        torch.zeros_like(submerged_w),
    )

    tx, tz = _unit_tangents_b(x_abs, z_abs)
    v_t = x_vel * tx + z_vel * tz
    v_n = -x_vel * tz + z_vel * tx
    A_n = graph.diameter * node_len
    A_t = math.pi * graph.diameter * node_len
    F_drag_t = -0.5 * S1.RHO_WATER * graph.Cd_t * A_t * v_t * v_t.abs()
    F_drag_n = -0.5 * S1.RHO_WATER * graph.Cd_n * A_n * v_n * v_n.abs()

    dyn = torch.stack([x_abs, z_abs, x_vel, z_vel, contact_flag, penetration, bed_reaction,
                       F_drag_t, F_drag_n], dim=-1)
    env = env_row.view(1, 1, 1, -1).expand(dyn.shape[0], dyn.shape[1], n, -1)
    return torch.cat([dyn, env], dim=-1)


def design(graph, dyn, blocks, lags=LAGS, rows=None):
    """Design matrix [B, R, N, P] (float32) for the requested blocks.

    rows: the time rows to keep (None = all). Lagged values are taken from the whole window
    and clamped at its edges -- the linear filter, like the BiLSTM, sees only the window."""
    b, w, n, _ = dyn.shape
    t_idx = torch.arange(w) if rows is None else torch.as_tensor(rows, dtype=torch.long)
    r = t_idx.numel()
    base = dyn[..., :N_BASE]
    parts = []
    if "own" in blocks:
        parts.append(graph.x.view(1, 1, n, N_STATIC).expand(b, r, n, N_STATIC))
        parts.append(dyn[:, t_idx])
    if "ctx" in blocks:
        br = base[:, t_idx]
        prev_i = torch.clamp(torch.arange(n) - 1, 0, n - 1)
        next_i = torch.clamp(torch.arange(n) + 1, 0, n - 1)
        parts += [br[:, :, n - 1:n].expand(b, r, n, N_BASE), br[:, :, prev_i], br[:, :, next_i],
                  br.mean(dim=2, keepdim=True).expand(b, r, n, N_BASE)]
    if "lag" in blocks:
        for tau in lags:
            ti = torch.clamp(t_idx + tau, 0, w - 1)
            lb = base[:, ti]
            parts += [lb, lb[:, :, n - 1:n].expand(b, r, n, N_BASE)]
    return torch.cat(parts, dim=-1)


def static_prediction(graph, w_len):
    """LR0: the station's static tension, held constant over the window, [W, N]."""
    t0 = graph.x[:, 11]
    return t0.view(1, -1).expand(w_len, -1)


# ----------------------------------------------------------------------------- workers
def worker_init(n_threads=1):
    """One BLAS/torch thread per worker, so a pool of workers does not oversubscribe."""
    torch.set_num_threads(n_threads)
    try:
        from threadpoolctl import threadpool_limits
        global _TPL
        _TPL = threadpool_limits(n_threads)
    except ImportError:
        pass


def _by_case(keys):
    """Group window keys as {(loc, case): {N: [starts]}} keeping first-seen order."""
    g = collections.OrderedDict()
    for lc, case, nc, s in keys:
        g.setdefault((lc, case), collections.OrderedDict()).setdefault(nc, []).append(s)
    return g


def make_tasks(kind, keys, cases_per_task, **extra):
    """Split window keys into tasks of `cases_per_task` cases of one location each."""
    grouped = _by_case(keys)
    by_loc = collections.OrderedDict()
    for (lc, case), per_n in grouped.items():
        by_loc.setdefault(lc, []).append((case, [(nc, st) for nc, st in per_n.items()]))
    tasks = []
    for lc in sorted(by_loc):
        cl = by_loc[lc]
        for i in range(0, len(cl), cases_per_task):
            tasks.append(dict(kind=kind, lc=lc, cases=cl[i:i + cases_per_task],
                              tid=f"{kind}_{lc:02d}_{i // cases_per_task:03d}", **extra))
    return tasks


def _chunk(n_rows_per_window, n_stations, p, budget_bytes=160e6, cap=16):
    per = n_rows_per_window * n_stations * (p + 1) * 8.0
    return max(1, min(cap, int(budget_bytes // max(per, 1.0))))


def _phase_rows(start, w_len, stride):
    """Rows of a window whose ABSOLUTE sample index is a multiple of `stride`, so windows
    that overlap keep the same samples."""
    first = (-int(start)) % stride
    return np.arange(first, w_len, stride)


def _qr_update(R, M):
    """Triangular factor of [R; M] (Householder QR, LAPACK geqrf)."""
    return np.linalg.qr(M if R is None else np.vstack([R, M]), mode="r")


def _square(R, q):
    """Pad a factor built from fewer than q rows to q x q."""
    if R is None:
        return np.zeros((q, q))
    if R.shape[0] < q:
        R = np.vstack([R, np.zeros((q - R.shape[0], q))])
    return R


def _fit_task(task):
    """Least-squares factor (or raw column moments) over the task's windows.

    kind 'moments': sum and sum of squares of every raw design column.
    kind 'fit'    : triangular factor R of the rows [1, z, y], z = (x - mu) / sd, per group
                    (the two halves of the LR3 pass; one group otherwise)."""
    cache, lc = task["cache_dir"], task["lc"]
    blocks, lags = task["blocks"], tuple(task.get("lags", LAGS))
    stride = int(task.get("stride", 1))
    group_of = task.get("group_of")          # {(case, N, start): 0 or 1}, LR3 pass only
    p = n_cols(blocks, lags)
    q = p + 2
    n_groups = int(task.get("n_groups", 1))
    if task["kind"] == "moments":
        s1, s2, cnt = np.zeros(p), np.zeros(p), 0
    else:
        mu, sd = np.asarray(task["mu"])[:p], np.asarray(task["sd"])[:p]
        R = [None] * n_groups
        cnt_g = np.zeros(n_groups)
    n_windows = 0
    for case, per_n in task["cases"]:
        arr = load_case(cache, lc, case)
        env_row = torch.tensor(arr["env"], dtype=torch.float32)
        for nc, starts in per_n:
            graph = case_graph(arr, lc, case, nc)
            rec = resampled_record(arr, nc)
            # windows grouped by (row phase, group) so a batch shares its rows
            buckets = collections.defaultdict(list)
            for s in starts:
                ph = (-int(s)) % stride
                grp = 0 if group_of is None else int(group_of[(case, nc, s)])
                buckets[(ph, grp)].append(s)
            for (ph, grp), ss in buckets.items():
                rows = None if stride == 1 else _phase_rows(ss[0], WINDOW_LEN, stride)
                r = WINDOW_LEN if rows is None else len(rows)
                # a larger block per QR update for a wide design (LR4): re-factoring the
                # stacked R costs ~q/rows of the update, so a block should hold >> q rows
                step = _chunk(r, nc, q, budget_bytes=float(task.get("budget_bytes", 100e6)),
                              cap=int(task.get("chunk_cap", 16)))
                for i in range(0, len(ss), step):
                    st = torch.tensor(ss[i:i + step])
                    idx = st[:, None] + torch.arange(WINDOW_LEN)[None]
                    dyn = batched_dynamic_features(rec["x"][idx], rec["z"][idx], graph, env_row)
                    X = design(graph, dyn, blocks, lags, rows).reshape(-1, p).numpy().astype(np.float64)
                    tw = rec["T"][idx] if rows is None else rec["T"][idx][:, torch.as_tensor(rows)]
                    y = tw.reshape(-1).numpy().astype(np.float64)
                    n_windows += len(st)
                    if task["kind"] == "moments":
                        s1 += X.sum(axis=0)
                        s2 += np.einsum("ij,ij->j", X, X)
                        cnt += X.shape[0]
                    else:
                        M = np.empty((X.shape[0], q))
                        M[:, 0] = 1.0
                        np.subtract(X, mu, out=M[:, 1:p + 1])
                        M[:, 1:p + 1] /= sd
                        M[:, -1] = y
                        R[grp] = _qr_update(R[grp], M)
                        cnt_g[grp] += y.size
    if task["kind"] == "moments":
        return dict(s1=s1, s2=s2, n=cnt, n_windows=n_windows)
    return dict(R=np.stack([_square(r, q) for r in R]), n=cnt_g, n_windows=n_windows)


def _target_norm():
    tn = S1.FeatureStandardizer((0,))
    tn.mean = torch.tensor([TARGET_MEAN], dtype=torch.float32)
    tn.std = torch.tensor([TARGET_STD], dtype=torch.float32)
    return tn


def regime_entries(contact_wn, yt_wn, yh_wn):
    """Per-station R^2 binned by seabed-contact regime, as in evaluate() (patch 16).

    contact_wn: the raw 0/1 contact flag [W, N]; yt/yh: NORMALISED tension [W, N]
    (station R^2 is affine-invariant; the 1e-8 validity floor is in normalised units)."""
    _frac = contact_wn.float().mean(dim=0)
    _ssr = ((yh_wn - yt_wn) ** 2).sum(dim=0)
    _sst = ((yt_wn - yt_wn.mean(dim=0, keepdim=True)) ** 2).sum(dim=0)
    _r2n = 1.0 - _ssr / _sst.clamp_min(1e-8)
    out = []
    for fv, r2, ok in zip(_frac.tolist(), _r2n.tolist(), (_sst > 1e-8).tolist()):
        if not ok:
            continue
        out.append(("grounded" if fv >= 0.98 else "touchdown" if fv > 0.02 else "suspended", r2))
    return out


def _eval_task(task):
    """Predictions of every rung on the task's windows, and per-window results.

    Returns {key: {rung: (m, regime, dump)}}, key = (loc, case, N, start).

    The rungs are nested: one design (the widest blocks, the longest lag set, whose leading
    columns are every shorter lag set's) serves them all, each rung reading its leading
    columns. Weights are on standardised inputs: (mu, sd) by default, or the rung's own pair
    in task['stand'] (LR4 has its own standardiser, so LR0-LR3 stay exactly as before)."""
    cache, lc = task["cache_dir"], task["lc"]
    weights = {k: np.asarray(v) for k, v in task["weights"].items()}    # standardised, [1+p]
    mu, sd = np.asarray(task["mu"]), np.asarray(task["sd"])
    rungs = task["rungs"]
    r_lags = {r: tuple(task.get("rung_lags", {}).get(r, task.get("lags", LAGS))) for r in rungs}
    stand = {r: (np.asarray(m_), np.asarray(s_)) for r, (m_, s_) in task.get("stand", {}).items()}
    fitted = [r for r in rungs if r != "LR0_static"]
    lags = max((r_lags[r] for r in fitted), key=len) if fitted else LAGS
    assert all(lags[:len(r_lags[r])] == r_lags[r] for r in fitted), "lag sets are not nested"
    blocks = max((RUNGS[r] for r in rungs), key=len)     # the rungs are nested
    p_full = n_cols(blocks, lags)
    p_of = {r: n_cols(RUNGS[r], r_lags[r]) for r in fitted}
    p_def = max([p_of[r] for r in fitted if r not in stand], default=0)
    snap_times = task["snap_times"]
    mape_min = float(task["mape_min"])
    tn = _target_norm()
    out = {}
    for case, per_n in task["cases"]:
        arr = load_case(cache, lc, case)
        env_row = torch.tensor(arr["env"], dtype=torch.float32)
        evs = snap_times.get((lc, case), [])
        for nc, starts in per_n:
            graph = case_graph(arr, lc, case, nc)
            rec = resampled_record(arr, nc)
            step = _chunk(WINDOW_LEN, nc, p_full, budget_bytes=120e6, cap=8)
            for i in range(0, len(starts), step):
                st = torch.tensor(starts[i:i + step])
                idx = st[:, None] + torch.arange(WINDOW_LEN)[None]
                dyn = batched_dynamic_features(rec["x"][idx], rec["z"][idx], graph, env_row)
                X = design(graph, dyn, blocks, lags).numpy().astype(np.float64)   # [B,W,N,P]
                Z = (X[..., :p_def] - mu[:p_def]) / sd[:p_def]
                Zr = {r: (X[..., :p_of[r]] - m_[:p_of[r]]) / s_[:p_of[r]] for r, (m_, s_) in stand.items()}
                del X
                y_true = rec["T"][idx]                                              # [B,W,N]
                for j, s in enumerate(st.tolist()):
                    key = (lc, case, nc, int(s))
                    yt_n = tn.transform(y_true[j].unsqueeze(-1))                   # [W,N,1]
                    true_w = tn.inverse_transform(yt_n)[..., 0].numpy()
                    contact = dyn[j, :, :, CONTACT_FLAG_IDX]
                    ev_rows = [int(t) - int(s) for t in evs if int(s) <= int(t) < int(s) + WINDOW_LEN]
                    res = {}
                    for rung in rungs:
                        if rung == "LR0_static":
                            pred = static_prediction(graph, WINDOW_LEN).double()
                        else:
                            p = p_of[rung]
                            wv = weights[rung]
                            zz = Zr[rung] if rung in Zr else Z
                            pred = torch.from_numpy(wv[0] + zz[j, :, :, :p] @ wv[1:])
                        yh_n = tn.transform(pred.float().unsqueeze(-1))
                        m = S1.compute_physical_metrics_per_target(
                            y_hat_norm=yh_n, y_true_norm=yt_n, target_norm=tn,
                            target_names=["tension"], mape_min=mape_min)
                        reg = regime_entries(contact, yt_n[..., 0], yh_n[..., 0])
                        pred_w = tn.inverse_transform(yh_n)[..., 0].numpy()
                        res[rung] = (m, reg, _dump_row(true_w, pred_w, ev_rows, key))
                    out[key] = res
    return out


def _dump_row(true_w, pred_w, ev_rows, key):
    """Per-window scalars of the Stage-1 test dump (cell pubts01, patches 23/27/sr-20)."""
    lc, case, nc, s = key
    snaps = []
    for r in ev_rows:
        n_st = int(true_w.shape[1])
        tt = np.full((len(SNAP_NBHD_OFF), SNAP_NBHD_MAXN), np.nan, np.float32)
        pp = np.full((len(SNAP_NBHD_OFF), SNAP_NBHD_MAXN), np.nan, np.float32)
        for j, o in enumerate(SNAP_NBHD_OFF):
            if 0 <= r + o < int(true_w.shape[0]):
                tt[j, :n_st] = true_w[r + o]
                pp[j, :n_st] = pred_w[r + o]
        snaps.append(((lc, case, nc, s, s + r), float(true_w[r].max()), float(pred_w[r].max()),
                      tt, pp, n_st))
    return dict(fl_true=float(true_w[:, -1].max()), fl_pred=float(pred_w[:, -1].max()),
                lp_true=float(true_w.max()), lp_pred=float(pred_w.max()), snaps=snaps)


