    def __init__(self, target_names=("tension",)):
        from collections import defaultdict as _dd
        self.target_names = list(target_names)
        tn = self.target_names
        self.num_windows = 0
        self.struct_sums = {
            "MAE": {n: 0.0 for n in tn}, "RMSE": {n: 0.0 for n in tn}, "R2": {n: 0.0 for n in tn},
            "ss_res": {n: 0.0 for n in tn}, "y_sum": {n: 0.0 for n in tn},
            "y_sq": {n: 0.0 for n in tn}, "n_pts": {n: 0.0 for n in tn},
        }
        self.flat_sums, self.flat_counts = {}, {}
        self.all_peak_abs_errors, self.all_peak_true_peaks, self.all_peak_signed_errors = [], [], []
        self._regime_r2 = {"grounded": [], "touchdown": [], "suspended": []}
        self.nc_struct = _dd(lambda: {k: {n: 0.0 for n in tn}
                                      for k in ("MAE", "RMSE", "R2", "ss_res", "y_sum", "y_sq", "n_pts")})
        self.nc_flat, self.nc_flat_c = _dd(dict), _dd(dict)
        self.nc_peak_abs, self.nc_peak_true, self.nc_peak_signed = _dd(list), _dd(list), _dd(list)
        self.nc_nb = _dd(int)
        self.per_window_rows = []

    def add(self, m, regime, key):
        import math as _math
        lc, case, nc_val, start = key
        target_names = self.target_names
        self.num_windows += 1
        for rg, r2 in regime:
            self._regime_r2[rg].append(r2)
        for metric in ("MAE", "RMSE", "R2"):
            for n in target_names:
                self.struct_sums[metric][n] += m[metric][n]
        for rk in ("ss_res", "y_sum", "y_sq"):
            for n in target_names:
                self.struct_sums[rk][n] += m[rk][n]
        for n in target_names:
            self.struct_sums["n_pts"][n] += m["n_pts"]
        self.all_peak_abs_errors.extend(m.get("peak_tension_abs_errors", []))
        self.all_peak_true_peaks.extend(m.get("peak_tension_true_peaks", []))
        self.all_peak_signed_errors.extend(m.get("peak_tension_signed_errors", []))

        _pwn = target_names[0]
        self.per_window_rows.append({
            "lc_id": lc, "case_id": case, "n_in": nc_val, "out_N": nc_val, "start_idx": start,
            "n_pts": m["n_pts"], "ss_res": m["ss_res"][_pwn], "y_sum": m["y_sum"][_pwn],
            "y_sq": m["y_sq"][_pwn], "mae": m["MAE"][_pwn], "rmse": m["RMSE"][_pwn],
            "r2": m["R2"][_pwn],
            "mape": m["MAPE"].get(_pwn, float("nan")),
            "mape_valid_frac": m["MAPE"].get(_pwn + "_valid_frac", float("nan")),
            "td_mae": m.get("temporal_diff_MAE_" + _pwn, float("nan")),
            "td_mae_flat": m.get("temporal_diff_MAE_flat_" + _pwn, float("nan")),
            "td_skill": m.get("temporal_diff_skill_" + _pwn, float("nan")),
            "peak_MAE": m.get("peak_tension_MAE", float("nan")),
            "peak_bias": m.get("peak_tension_bias", float("nan")),
        })

        _skip = {"MAE", "RMSE", "R2", "MAPE", "ss_res", "y_sum", "y_sq",
                 "n_pts", "peak_tension_abs_errors", "peak_tension_true_peaks", "peak_tension_signed_errors"}
        flat_keys = list(m["MAPE"].keys()) + [k for k in m if k not in _skip]
        for k in flat_keys:
            val = m["MAPE"].get(k) if k in m["MAPE"] else m[k]
            if k not in self.flat_sums:
                self.flat_sums[k] = 0.0
                self.flat_counts[k] = 0
            if not _math.isnan(val):
                self.flat_sums[k] += val
                self.flat_counts[k] += 1

        self.nc_nb[nc_val] += 1
        for metric in ("MAE", "RMSE", "R2"):
            for n in target_names:
                self.nc_struct[nc_val][metric][n] += m[metric][n]
        for rk in ("ss_res", "y_sum", "y_sq"):
            for n in target_names:
                self.nc_struct[nc_val][rk][n] += m[rk][n]
        for n in target_names:
            self.nc_struct[nc_val]["n_pts"][n] += m["n_pts"]
        self.nc_peak_abs[nc_val].extend(m.get("peak_tension_abs_errors", []))
        self.nc_peak_true[nc_val].extend(m.get("peak_tension_true_peaks", []))
        self.nc_peak_signed[nc_val].extend(m.get("peak_tension_signed_errors", []))
        for k in flat_keys:
            val = m["MAPE"].get(k) if k in m["MAPE"] else m[k]
            if k not in self.nc_flat[nc_val]:
                self.nc_flat[nc_val][k] = 0.0
                self.nc_flat_c[nc_val][k] = 0
            if not _math.isnan(val):
                self.nc_flat[nc_val][k] += val
                self.nc_flat_c[nc_val][k] += 1

    def finalize(self):
        target_names = self.target_names
        _meps = 1e-8

        def _global_r2(ss_d, ys_d, yq_d, np_d, tnames):
            out = {}
            for n in tnames:
                n_t = np_d[n]
                if n_t < 2:
                    out[n] = float("nan"); continue
                gm = ys_d[n] / n_t
                ss_tot = yq_d[n] - n_t * gm ** 2
                out[n] = float(1.0 - ss_d[n] / max(ss_tot, _meps))
            return out

        def _agg_p95_max(errs):
            if not errs:
                return float("nan"), float("nan")
            se = sorted(errs)
            return float(se[max(0, int(0.95 * len(se)) - 1)]), float(se[-1])

        def _peak_tail_stats(true_pk, signed_err, q):
            if not true_pk:
                return (float("nan"),) * 5
            pairs = sorted(zip(true_pk, signed_err), key=lambda t: t[0])
            k = max(1, int(round((1.0 - q) * len(pairs))))
            tail = pairs[len(pairs) - k:]
            thr = float(tail[0][0])
            errs = [e for _t, e in tail]
            under = 100.0 * sum(1 for e in errs if e < 0) / len(errs)
            bias = float(sum(errs) / len(errs))
            mae = float(sum(abs(e) for e in errs) / len(errs))
            _neg = [abs(e) for e in errs if e < 0]
            undermag = float(sum(_neg) / len(_neg)) if _neg else 0.0
            return thr, under, bias, mae, undermag

        def _build_avg(struct_s, flat_s, flat_c, nb, pk_list):
            avg = {
                "MAE": {n: struct_s["MAE"][n] / max(1, nb) for n in target_names},
                "RMSE": {n: struct_s["RMSE"][n] / max(1, nb) for n in target_names},
                "R2": {n: struct_s["R2"][n] / max(1, nb) for n in target_names},
                "global_R2": _global_r2(struct_s["ss_res"], struct_s["y_sum"], struct_s["y_sq"],
                                        struct_s["n_pts"], target_names),
                "MAPE": {},
            }
            for k, s in flat_s.items():
                cnt = flat_c[k]
                val = s / cnt if cnt > 0 else float("nan")
                if k in ("tension", "tension_valid_frac"):
                    avg["MAPE"][k] = val
                else:
                    avg[k] = val
            p95, pmax = _agg_p95_max(pk_list)
            avg["peak_tension_p95_abs_error"] = p95
            avg["peak_tension_max_abs_error"] = pmax
            return avg

        avg_metrics = _build_avg(self.struct_sums, self.flat_sums, self.flat_counts,
                                 self.num_windows, self.all_peak_abs_errors)
        for _q, _tag in ((0.90, "p90"), (0.99, "p99")):
            _thr, _und, _bias, _mae, _umag = _peak_tail_stats(
                self.all_peak_true_peaks, self.all_peak_signed_errors, _q)
            avg_metrics[f"peak_tension_thr_{_tag}"] = _thr
            avg_metrics[f"peak_tension_underpred_rate_{_tag}"] = _und
            avg_metrics[f"peak_tension_bias_{_tag}"] = _bias
            avg_metrics[f"peak_tension_MAE_{_tag}"] = _mae
            avg_metrics[f"peak_tension_undermag_{_tag}"] = _umag
        for _rg in ("grounded", "touchdown", "suspended"):
            _vals = self._regime_r2[_rg]
            if _vals:
                avg_metrics[f"contact_{_rg}_R2_median"] = float(statistics.median(_vals))
                avg_metrics[f"contact_{_rg}_R2_fracneg"] = float(
                    100.0 * sum(1 for v in _vals if v < 0) / len(_vals))
                avg_metrics[f"contact_{_rg}_n"] = len(_vals)
            else:
                avg_metrics[f"contact_{_rg}_R2_median"] = float("nan")
                avg_metrics[f"contact_{_rg}_R2_fracneg"] = float("nan")
                avg_metrics[f"contact_{_rg}_n"] = 0
        per_nc = {}
        for nc_key, nb_val in self.nc_nb.items():
            _m_nc = _build_avg(self.nc_struct[nc_key], self.nc_flat[nc_key],
                               self.nc_flat_c[nc_key], nb_val, self.nc_peak_abs[nc_key])
            for _q, _tag in ((0.90, "p90"), (0.99, "p99")):
                _t, _u, _b, _ma, _um = _peak_tail_stats(
                    self.nc_peak_true[nc_key], self.nc_peak_signed[nc_key], _q)
                _m_nc[f"peak_tension_thr_{_tag}"] = _t
                _m_nc[f"peak_tension_underpred_rate_{_tag}"] = _u
                _m_nc[f"peak_tension_bias_{_tag}"] = _b
                _m_nc[f"peak_tension_MAE_{_tag}"] = _ma
                _m_nc[f"peak_tension_undermag_{_tag}"] = _um
            per_nc[nc_key] = _m_nc
        return avg_metrics, per_nc


